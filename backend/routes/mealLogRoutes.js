
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const multer = require('multer');

// ======================================================
// MEAL PHOTO STORAGE
// ======================================================

// Store photos in the backend, not the frontend.
const MEAL_PHOTOS_DIR = path.join(
    __dirname,
    '..',
    'uploads',
    'meal-photos'
);

// Create the folder automatically if missing.
fs.mkdirSync(MEAL_PHOTOS_DIR, {
    recursive: true
});

// Maximum image size: 5 MB.
const mealPhotoUpload = multer({
    storage: multer.memoryStorage(),

    limits: {
        fileSize: 5 * 1024 * 1024,
        files: 1,
        fields: 20,
        fieldSize: 16384
    }
});

// ======================================================
// VERIFY IMAGE FILE SIGNATURE
// ======================================================

function inspectMealPhoto(buffer) {

    if (
        !Buffer.isBuffer(buffer) ||
        buffer.length < 12
    ) {
        return null;
    }

    // JPEG
    if (
        buffer[0] === 0xff &&
        buffer[1] === 0xd8 &&
        buffer[2] === 0xff
    ) {
        return {
            extension: 'jpg',
            mime: 'image/jpeg'
        };
    }

    // PNG
    if (
        buffer.subarray(0, 8).equals(
            Buffer.from([
                137, 80, 78, 71,
                13, 10, 26, 10
            ])
        )
    ) {
        return {
            extension: 'png',
            mime: 'image/png'
        };
    }

    // WebP
    if (
        buffer.toString('ascii', 0, 4) === 'RIFF' &&
        buffer.toString('ascii', 8, 12) === 'WEBP'
    ) {
        return {
            extension: 'webp',
            mime: 'image/webp'
        };
    }

    return null;
}

// Only filenames generated by this backend are accepted.
const mealPhotoFilenameRegex =
    /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}\.(jpg|png|webp)$/i;


const express =
    require('express');

const {
    roundOne
} =
    require('../helpers/generalHelpers');

const {
    normalizeFoodKey
} =
    require('../helpers/nutritionHelpers');


// ======================================================
// MEAL LOG / DASHBOARD ROUTES
// ======================================================

function createMealLogRouter({
    db,
    authenticateToken
}) {

    const router =
        express.Router();


    // ======================================================
    // SAVE MEAL
    // ======================================================

    router.post(
        '/meal-logs',

        authenticateToken,

        // Accept uploaded photo from AI Scanner.
        // Existing JSON requests still work.
        mealPhotoUpload.single('image'),


        async (req, res) => {

            const {
                foodKey,
                foodName,
                mealType,
                sourceType,
                portionGrams,
                calories,
                protein,
                carbs,
                fat,
                aiConfidence,
                imageUrl
            } =
                req.body;

            
            // ======================================================
            // VALIDATE UPLOADED MEAL PHOTO
            // ======================================================

            let photoDetails = null;

            if (req.file) {

                photoDetails = inspectMealPhoto(
                    req.file.buffer
                );

                const allowedMimeTypes = [
                    'image/jpeg',
                    'image/png',
                    'image/webp'
                ];

                if (
                    sourceType !== 'meal_scanner' ||
                    !photoDetails ||
                    !allowedMimeTypes.includes(
                        req.file.mimetype
                    ) ||
                    req.file.mimetype !== photoDetails.mime
                ) {

                    return res.status(400).json({
                        success: false,
                        message:
                            'Meal photos must be JPEG, PNG or WebP images.'
                    });
                }
            }

            // ======================================================
            // VALIDATE EXISTING RECIPE IMAGE URL
            // ======================================================

            // Recipe meal logging can still send JSON.
            // Do not store temporary browser preview URLs.

            
            if (
                !req.file &&
                imageUrl != null &&
                imageUrl !== ''
            ) {

                // ==============================================
                // RECOGNIZE PRIVATE RECIPE PHOTO
                // ==============================================

                const isPrivateRecipePhoto =
                    typeof imageUrl === 'string' &&
                    /^\/api\/recipe-photos\/[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}\.(jpg|png|webp)$/i
                        .test(imageUrl);

                // Keep support for existing public images.
                const isPublicImage =
                    typeof imageUrl === 'string' &&
                    (
                        /^https?:\/\//i.test(imageUrl) ||
                        imageUrl.startsWith('/generated-images/')
                    );

                // ==============================================
                // VALIDATE IMAGE URL
                // ==============================================

                if (
                    typeof imageUrl !== 'string' ||
                    imageUrl.length > 500 ||
                    (!isPrivateRecipePhoto && !isPublicImage)
                ) {

                    return res.status(400).json({
                        success: false,
                        message: 'Invalid meal image URL.'
                    });
                }

                // ==============================================
                // VERIFY PRIVATE RECIPE PHOTO OWNERSHIP
                // ==============================================

                if (isPrivateRecipePhoto) {

                    // Private recipe photos can only be used
                    // when logging a meal from a saved recipe.
                    if (sourceType !== 'recipe') {

                        return res.status(400).json({
                            success: false,
                            message:
                                'Recipe photos can only be logged with recipe meals.'
                        });
                    }

                    let ownedRecipes;

                    try {

                        ownedRecipes = await new Promise(
                            (resolve, reject) => {

                                db.query(
                                    `
                                    SELECT id
                                    FROM saved_recipes
                                    WHERE user_id = ?
                                    AND image_url = ?
                                    LIMIT 1
                                    `,
                                    [
                                        req.user.id,
                                        imageUrl
                                    ],
                                    (error, rows) => {

                                        if (error) {
                                            reject(error);
                                        } else {
                                            resolve(rows);
                                        }
                                    }
                                );
                            }
                        );

                    } catch (lookupError) {

                        console.error(
                            'Recipe photo verification:',
                            lookupError
                        );

                        return res.status(500).json({
                            success: false,
                            message:
                                'Unable to verify recipe photo.'
                        });
                    }

                    // The user must own the saved recipe
                    // that contains this image.
                    if (!ownedRecipes.length) {

                        return res.status(404).json({
                            success: false,
                            message:
                                'Recipe photo not found in your saved recipes.'
                        });
                    }
                }
            }




            const allowedMealTypes = [
                'breakfast',
                'lunch',
                'dinner',
                'snack'
            ];


            const allowedSources = [
                'meal_scanner',
                'recipe',
                'manual'
            ];


            if (
                !foodName ||
                !allowedMealTypes.includes(
                    mealType
                )
            ) {
                return res
                    .status(400)
                    .json({
                        message:
                            'Food name and valid meal type are required.'
                    });
            }


            const numericCalories =
                Number(calories);

            const numericProtein =
                Number(
                    protein || 0
                );

            const numericCarbs =
                Number(
                    carbs || 0
                );

            const numericFat =
                Number(
                    fat || 0
                );


            if (
                !Number.isFinite(
                    numericCalories
                ) ||
                numericCalories < 0 ||
                !Number.isFinite(
                    numericProtein
                ) ||
                numericProtein < 0 ||
                !Number.isFinite(
                    numericCarbs
                ) ||
                numericCarbs < 0 ||
                !Number.isFinite(
                    numericFat
                ) ||
                numericFat < 0
            ) {
                return res
                    .status(400)
                    .json({
                        message:
                            'Invalid nutrition values.'
                    });
            }

            
            // ======================================================
            // SAVE MEAL PHOTO TO BACKEND STORAGE
            // ======================================================

            let storedPhotoPath = null;

            // Existing recipe JSON requests may supply imageUrl.
            let savedImageUrl = imageUrl || null;

            if (req.file) {

                // Generate a safe, unique photo filename.
                const filename =
                    `${crypto.randomUUID()}.${photoDetails.extension}`;

                storedPhotoPath = path.join(
                    MEAL_PHOTOS_DIR,
                    filename
                );

                // Save this URL in MySQL.
                savedImageUrl =
                    `/api/meal-photos/${filename}`;

                try {

                    await fs.promises.writeFile(
                        storedPhotoPath,
                        req.file.buffer,
                        {
                            flag: 'wx',
                            mode: 0o600
                        }
                    );

                } catch (writeError) {

                    console.error(
                        'Meal photo write failed:',
                        writeError
                    );

                    return res.status(500).json({
                        success: false,
                        message: 'Unable to save meal photo.'
                    });
                }
            }



            db.query(
                `
                INSERT INTO meal_logs
                (
                    user_id,
                    food_key,
                    food_name,
                    meal_type,
                    source_type,
                    portion_grams,
                    calories,
                    protein_grams,
                    carbs_grams,
                    fat_grams,
                    ai_confidence,
                    image_url
                )
                VALUES
                (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                `,
                [
                    req.user.id,

                    foodKey
                        ? normalizeFoodKey(
                            foodKey
                        )
                        : null,

                    String(
                        foodName
                    ).trim(),

                    mealType,

                    allowedSources.includes(
                        sourceType
                    )
                        ? sourceType
                        : 'manual',

                    portionGrams
                        ? Number(
                            portionGrams
                        )
                        : null,

                    roundOne(
                        numericCalories
                    ),

                    roundOne(
                        numericProtein
                    ),

                    roundOne(
                        numericCarbs
                    ),

                    roundOne(
                        numericFat
                    ),

                    aiConfidence !==
                    undefined &&
                    aiConfidence !==
                    null
                        ? Number(
                            aiConfidence
                        )
                        : null,

                    savedImageUrl
                ],

                (
                    error,
                    result
                ) => {

                    
                    if (error) {

                        console.error(error);

                        // Remove the photo if MySQL could not save
                        // the associated meal record.
                        if (storedPhotoPath) {

                            fs.promises.unlink(
                                storedPhotoPath
                            ).catch(cleanupError => {

                                console.error(
                                    'Meal photo cleanup failed:',
                                    cleanupError
                                );

                            });
                        }

                        return res.status(500).json({
                            success: false,
                            message: 'Unable to save meal.'
                        });
                    }



                    return res
                        .status(201)
                        .json({
                            success: true,

                            mealLogId:
                                result.insertId
                        });
                }
            );
        }
    );
    
    
    // ======================================================
    // PRIVATE MEAL PHOTO RETRIEVAL
    //
    // GET /api/meal-photos/:filename
    //
    // Only the meal owner can access the photo.
    // ======================================================

    router.get(
        '/meal-photos/:filename',

        authenticateToken,

        (req, res) => {

            const filename = String(
                req.params.filename || ''
            );

            // ==============================================
            // VALIDATE FILENAME
            // ==============================================

            if (
                !mealPhotoFilenameRegex.test(filename)
            ) {

                return res.status(400).json({
                    success: false,
                    message: 'Invalid meal photo name.'
                });
            }

            const photoUrl =
                `/api/meal-photos/${filename}`;

            // ==============================================
            // CHECK MEAL OWNERSHIP IN MYSQL
            // ==============================================

            db.query(
                `
                SELECT id
                FROM meal_logs
                WHERE user_id = ?
                AND image_url = ?
                LIMIT 1
                `,

                [
                    req.user.id,
                    photoUrl
                ],

                (error, rows) => {

                    if (error) {

                        console.error(
                            'Meal photo lookup:',
                            error
                        );

                        return res.status(500).json({
                            success: false,
                            message:
                                'Unable to load meal photo.'
                        });
                    }

                    if (rows.length === 0) {

                        return res.status(404).json({
                            success: false,
                            message: 'Meal photo not found.'
                        });
                    }

                    // ======================================
                    // PREPARE PHOTO
                    // ======================================

                    const filePath = path.join(
                        MEAL_PHOTOS_DIR,
                        filename
                    );

                    const extension = path
                        .extname(filename)
                        .toLowerCase();

                    const mime =
                        extension === '.png'
                            ? 'image/png'
                            : extension === '.webp'
                                ? 'image/webp'
                                : 'image/jpeg';

                    // ======================================
                    // SEND IMAGE TO AUTHENTICATED USER
                    // ======================================

                    res.set({
                        'Cache-Control': 'private, no-store',
                        'X-Content-Type-Options': 'nosniff',
                        'Content-Type': mime
                    });

                    res.sendFile(
                        filePath,

                        (sendError) => {

                            if (
                                sendError &&
                                !res.headersSent
                            ) {

                                return res.status(404).json({
                                    success: false,
                                    message:
                                        'Meal photo file is missing.'
                                });
                            }
                        }
                    );
                }
            );
        }
    );


    // ======================================================
    // TODAY MEALS
    // ======================================================

    router.get(
        '/meal-logs/today',

        authenticateToken,

        (
            req,
            res
        ) => {

            db.query(
                `
                SELECT *
                FROM meal_logs
                WHERE user_id = ?
                AND DATE(logged_at) = CURDATE()
                ORDER BY logged_at ASC
                `,
                [
                    req.user.id
                ],

                (
                    error,
                    results
                ) => {

                    if (error) {
                        return res
                            .status(500)
                            .json({
                                message:
                                    'Unable to load meals.'
                            });
                    }


                    return res.json({
                        success: true,

                        meals:
                            results.map(
                                (meal) => ({
                                    id:
                                        meal.id,

                                    foodKey:
                                        meal.food_key,

                                    foodName:
                                        meal.food_name,

                                    mealType:
                                        meal.meal_type,

                                    sourceType:
                                        meal.source_type,

                                    portionGrams:
                                        meal.portion_grams !==
                                        null
                                            ? Number(
                                                meal.portion_grams
                                            )
                                            : null,

                                    calories:
                                        Number(
                                            meal.calories
                                        ),

                                    protein:
                                        Number(
                                            meal.protein_grams
                                        ),

                                    carbs:
                                        Number(
                                            meal.carbs_grams
                                        ),

                                    fat:
                                        Number(
                                            meal.fat_grams
                                        ),

                                    aiConfidence:
                                        meal.ai_confidence !==
                                        null
                                            ? Number(
                                                meal.ai_confidence
                                            )
                                            : null,

                                    imageUrl:
                                        meal.image_url,

                                    loggedAt:
                                        meal.logged_at
                                })
                            )
                    });
                }
            );
        }
    );


    // ======================================================
    // DAILY SUMMARY
    // ======================================================

    router.get(
        '/daily-summary',

        authenticateToken,

        (
            req,
            res
        ) => {

            db.query(
                `
                SELECT
                    u.id,
                    u.username,
                    u.full_name,
                    u.weight,
                    u.target_weight,
                    u.primary_goal,
                    u.bmi,
                    u.bmr,
                    u.tdee,
                    u.daily_calorie_target,
                    u.protein_target,
                    u.carbs_target,
                    u.fat_target,

                    COALESCE(
                        SUM(m.calories),
                        0
                    ) AS calories_consumed,

                    COALESCE(
                        SUM(m.protein_grams),
                        0
                    ) AS protein_consumed,

                    COALESCE(
                        SUM(m.carbs_grams),
                        0
                    ) AS carbs_consumed,

                    COALESCE(
                        SUM(m.fat_grams),
                        0
                    ) AS fat_consumed,

                    COUNT(m.id)
                        AS meals_logged

                FROM users u

                LEFT JOIN meal_logs m
                    ON m.user_id = u.id
                AND DATE(m.logged_at)
                    = CURDATE()

                WHERE u.id = ?

                GROUP BY
                    u.id,
                    u.username,
                    u.full_name,
                    u.weight,
                    u.target_weight,
                    u.primary_goal,
                    u.bmi,
                    u.bmr,
                    u.tdee,
                    u.daily_calorie_target,
                    u.protein_target,
                    u.carbs_target,
                    u.fat_target

                LIMIT 1
                `,
                [
                    req.user.id
                ],

                (
                    error,
                    results
                ) => {

                    if (
                        error ||
                        !results.length
                    ) {
                        return res
                            .status(
                                error
                                    ? 500
                                    : 404
                            )
                            .json({
                                message:
                                    'Unable to load daily summary.'
                            });
                    }


                    const row =
                        results[0];


                    const targets = {
                        calories:
                            Number(
                                row.daily_calorie_target ||
                                0
                            ),

                        protein:
                            Number(
                                row.protein_target ||
                                0
                            ),

                        carbs:
                            Number(
                                row.carbs_target ||
                                0
                            ),

                        fat:
                            Number(
                                row.fat_target ||
                                0
                            )
                    };


                    const consumed = {
                        calories:
                            Number(
                                row.calories_consumed ||
                                0
                            ),

                        protein:
                            Number(
                                row.protein_consumed ||
                                0
                            ),

                        carbs:
                            Number(
                                row.carbs_consumed ||
                                0
                            ),

                        fat:
                            Number(
                                row.fat_consumed ||
                                0
                            )
                    };


                    const percentage =
                        (
                            value,
                            target
                        ) =>
                            target > 0
                                ? roundOne(
                                    (
                                        value /
                                        target
                                    ) *
                                    100
                                )
                                : 0;


                    return res.json({
                        success: true,

                        profile: {
                            username:
                                row.username,

                            fullName:
                                row.full_name,

                            primaryGoal:
                                row.primary_goal,

                            currentWeight:
                                Number(
                                    row.weight ||
                                    0
                                ),

                            targetWeight:
                                Number(
                                    row.target_weight ||
                                    0
                                ),

                            bmi:
                                Number(
                                    row.bmi ||
                                    0
                                ),

                            bmr:
                                Number(
                                    row.bmr ||
                                    0
                                ),

                            tdee:
                                Number(
                                    row.tdee ||
                                    0
                                )
                        },

                        targets: {
                            calories:
                                roundOne(
                                    targets.calories
                                ),

                            protein:
                                roundOne(
                                    targets.protein
                                ),

                            carbs:
                                roundOne(
                                    targets.carbs
                                ),

                            fat:
                                roundOne(
                                    targets.fat
                                )
                        },

                        consumed: {
                            calories:
                                roundOne(
                                    consumed.calories
                                ),

                            protein:
                                roundOne(
                                    consumed.protein
                                ),

                            carbs:
                                roundOne(
                                    consumed.carbs
                                ),

                            fat:
                                roundOne(
                                    consumed.fat
                                )
                        },

                        remaining: {
                            calories:
                                roundOne(
                                    Math.max(
                                        0,
                                        targets.calories -
                                        consumed.calories
                                    )
                                ),

                            protein:
                                roundOne(
                                    Math.max(
                                        0,
                                        targets.protein -
                                        consumed.protein
                                    )
                                ),

                            carbs:
                                roundOne(
                                    Math.max(
                                        0,
                                        targets.carbs -
                                        consumed.carbs
                                    )
                                ),

                            fat:
                                roundOne(
                                    Math.max(
                                        0,
                                        targets.fat -
                                        consumed.fat
                                    )
                                )
                        },

                        progress: {
                            calories:
                                percentage(
                                    consumed.calories,
                                    targets.calories
                                ),

                            protein:
                                percentage(
                                    consumed.protein,
                                    targets.protein
                                ),

                            carbs:
                                percentage(
                                    consumed.carbs,
                                    targets.carbs
                                ),

                            fat:
                                percentage(
                                    consumed.fat,
                                    targets.fat
                                )
                        },

                        mealsLogged:
                            Number(
                                row.meals_logged ||
                                0
                            )
                    });
                }
            );
        }
    );


    
    // ======================================================
    // DELETE MEAL AND ITS UPLOADED PHOTO
    // ======================================================

    router.delete(
        '/meal-logs/:id',

        authenticateToken,

        (req, res) => {

            const mealId = Number(
                req.params.id
            );

            // ==============================================
            // VALIDATE MEAL ID
            // ==============================================

            if (
                !Number.isSafeInteger(mealId) ||
                mealId <= 0
            ) {

                return res.status(400).json({
                    success: false,
                    message: 'Invalid meal ID.'
                });
            }

            // ==============================================
            // CHECK MEAL EXISTS AND BELONGS TO USER
            // ==============================================

            db.query(
                `
                SELECT image_url
                FROM meal_logs
                WHERE id = ?
                AND user_id = ?
                LIMIT 1
                `,

                [
                    mealId,
                    req.user.id
                ],

                (lookupError, existingMeals) => {

                    if (lookupError) {

                        console.error(
                            'Meal lookup failed:',
                            lookupError
                        );

                        return res.status(500).json({
                            success: false,
                            message: 'Unable to remove meal.'
                        });
                    }

                    if (existingMeals.length === 0) {

                        return res.status(404).json({
                            success: false,
                            message: 'Meal log not found.'
                        });
                    }

                    const imageUrl =
                        existingMeals[0].image_url;

                    // ======================================
                    // DELETE MEAL FROM MYSQL
                    // ======================================

                    db.query(
                        `
                        DELETE FROM meal_logs
                        WHERE id = ?
                        AND user_id = ?
                        LIMIT 1
                        `,

                        [
                            mealId,
                            req.user.id
                        ],

                        (deleteError, result) => {

                            if (deleteError) {

                                console.error(
                                    'Meal delete failed:',
                                    deleteError
                                );

                                return res.status(500).json({
                                    success: false,
                                    message:
                                        'Unable to remove meal.'
                                });
                            }

                            if (result.affectedRows === 0) {

                                return res.status(404).json({
                                    success: false,
                                    message:
                                        'Meal log not found.'
                                });
                            }

                            // ==============================
                            // REMOVE UPLOADED PHOTO
                            // ==============================

                            const prefix =
                                '/api/meal-photos/';

                            // Only delete our private meal
                            // photos, not recipe images.

                            if (
                                typeof imageUrl === 'string' &&
                                imageUrl.startsWith(prefix)
                            ) {

                                const filename =
                                    imageUrl.slice(
                                        prefix.length
                                    );

                                if (
                                    mealPhotoFilenameRegex.test(
                                        filename
                                    )
                                ) {

                                    fs.promises.unlink(
                                        path.join(
                                            MEAL_PHOTOS_DIR,
                                            filename
                                        )
                                    ).catch(cleanupError => {

                                        if (
                                            cleanupError.code !==
                                            'ENOENT'
                                        ) {

                                            console.error(
                                                'Could not remove meal photo:',
                                                cleanupError
                                            );
                                        }
                                    });
                                }
                            }

                            // ==============================
                            // SUCCESS
                            // ==============================

                            return res.json({
                                success: true
                            });
                        }
                    );
                }
            );
        }
    );



    return router;
}


// ======================================================
// EXPORT
